function applyHongKongExperienceCopy() {
  if (typeof experiences === "undefined") return;

  experiences.forEach((experience) => {
    const translated = hkExperienceCopy[experience.id];
    if (!translated) return;
    Object.assign(experience, translated);
  });
}

function translatedText(value) {
  const normalized = value.replace(/\s+/g, " ").trim();
  if (!normalized) return value;

  let translated = hkExactText.get(normalized);
  if (!translated) {
    translated = normalized;
    hkPhraseFallback.forEach(([english, traditional]) => {
      translated = translated.split(english).join(traditional);
    });
  }

  if (translated === normalized) return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

function localiseHongKongPage() {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const tag = node.parentElement?.tagName;
        if (!node.nodeValue.trim() || tag === "SCRIPT" || tag === "STYLE") {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    },
  );

  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach((node) => {
    node.nodeValue = translatedText(node.nodeValue);
  });

  document
    .querySelectorAll("[aria-label], [alt], [title], [data-edit-label]")
    .forEach((element) => {
      ["aria-label", "alt", "title", "data-edit-label"].forEach((attribute) => {
        if (!element.hasAttribute(attribute)) return;
        element.setAttribute(
          attribute,
          translatedText(element.getAttribute(attribute)),
        );
      });
    });
}

document.addEventListener("DOMContentLoaded", () => {
  applyHongKongExperienceCopy();

  if (document.body.dataset.page === "experience") {
    renderExperience();
    const current = new URLSearchParams(window.location.search).get("id");
    const experience =
      experiences.find((item) => item.id === current) || experiences[0];
    document.title = `${experience.organization} | Aaron Li`;
  } else {
    renderHome();
    document.title = "Aaron Li | 顧問";
  }

  localiseHongKongPage();
});
